#!/usr/bin/env python3

"""
Generate a professional Markdown release document for Natrix.

Environment variables:
    TAG_NAME        Release tag/version.
    ARTIFACTS_PATH  Directory containing release artifacts.
    RELEASE_TYPE    Release classification (stable, beta, nightly, etc.).
    COMMIT_SHA      Git commit associated with the release.
    REPOSITORY      GitHub repository in OWNER/REPOSITORY format.
    RELEASE_DATE    Release date in ISO-8601 format.
"""

import os
from pathlib import Path


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

TAG_NAME = os.getenv("TAG_NAME", "unknown")
ARTIFACTS_PATH = Path(os.getenv("ARTIFACTS_PATH", "artifacts"))
RELEASE_TYPE = os.getenv("RELEASE_TYPE", "stable").lower()
COMMIT_SHA = os.getenv("COMMIT_SHA", "unknown")
REPOSITORY = os.getenv("REPOSITORY", "Extenporos/Natrix")
RELEASE_DATE = os.getenv("RELEASE_DATE", "unknown")

OUTPUT_FILE = Path("RELEASE_NOTES.md")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def format_size(size_bytes: int) -> str:
    """Convert a byte count into a human-readable size."""
    units = ("B", "KB", "MB", "GB", "TB")
    size = float(size_bytes)

    for unit in units:
        if size < 1024 or unit == units[-1]:
            return f"{size:.2f} {unit}"
        size /= 1024

    return f"{size:.2f} TB"


def markdown_escape(value: str) -> str:
    """Escape characters that can interfere with Markdown tables."""
    return value.replace("|", "\\|")


def github_artifact_url(repository: str, tag: str, filename: str) -> str:
    """Generate a GitHub release artifact URL."""
    return (
        f"https://github.com/{repository}/releases/download/"
        f"{tag}/{filename}"
    )


# ---------------------------------------------------------------------------
# Artifact discovery
# ---------------------------------------------------------------------------

def collect_artifacts() -> list[dict[str, str | int]]:
    """Discover and describe all files inside the artifact directory."""
    if not ARTIFACTS_PATH.exists():
        return []

    artifacts = []

    for file_path in ARTIFACTS_PATH.rglob("*"):
        if not file_path.is_file():
            continue

        size_bytes = file_path.stat().st_size

        artifacts.append(
            {
                "name": file_path.name,
                "path": str(file_path.relative_to(ARTIFACTS_PATH)),
                "size_bytes": size_bytes,
                "size": format_size(size_bytes),
            }
        )

    return sorted(
        artifacts,
        key=lambda artifact: artifact["name"].lower(),
    )


# ---------------------------------------------------------------------------
# Markdown generation
# ---------------------------------------------------------------------------

def generate_release_notes(
    artifacts: list[dict[str, str | int]],
) -> str:
    """Generate the complete release document."""

    release_title = f"Natrix {TAG_NAME}"

    if RELEASE_TYPE != "stable":
        release_title += f" — {RELEASE_TYPE.title()}"

    lines = [
        f"# {release_title}",
        "",
        "> Automated release documentation generated by the Natrix CI/CD pipeline.",
        "",
        "## Release Information",
        "",
        "| Property | Value |",
        "|----------|-------|",
        f"| **Version** | `{TAG_NAME}` |",
        f"| **Release Type** | `{RELEASE_TYPE}` |",
        f"| **Release Date** | `{RELEASE_DATE}` |",
        f"| **Commit** | `{COMMIT_SHA}` |",
        f"| **Repository** | `{REPOSITORY}` |",
        "",
        "## Overview",
        "",
        f"This document contains the release information and downloadable "
        f"artifacts for **Natrix `{TAG_NAME}`**.",
        "",
        "## Downloads",
        "",
    ]

    if not artifacts:
        lines.extend(
            [
                "> ⚠️ No release artifacts were found.",
                "",
            ]
        )
    else:
        lines.extend(
            [
                "| Artifact | Size | Download |",
                "|----------|------|----------|",
            ]
        )

        for artifact in artifacts:
            name = markdown_escape(str(artifact["name"]))
            size = str(artifact["size"])

            url = github_artifact_url(
                REPOSITORY,
                TAG_NAME,
                str(artifact["path"]),
            )

            lines.append(
                f"| `{name}` | {size} | "
                f"[Download](<{url}>) |"
            )

        lines.append("")

    lines.extend(
        [
            "## What's New",
            "",
            "<!--",
            "Add release-specific changes below.",
            "",
            "Example:",
            "- Added runtime discovery.",
            "- Improved environment management.",
            "- Fixed configuration loading.",
            "-->",
            "",
            "### Added",
            "",
            "- No release-specific additions documented.",
            "",
            "### Changed",
            "",
            "- No release-specific changes documented.",
            "",
            "### Fixed",
            "",
            "- No release-specific fixes documented.",
            "",
            "## Verification",
            "",
            "Release artifacts are generated and published by the "
            "Natrix CI/CD pipeline.",
            "",
            "For source code, issues, and development information, "
            f"visit the [Natrix repository](https://github.com/{REPOSITORY}).",
            "",
            "---",
            "",
            "*Generated automatically by `generate_md_release_notes.py`.*",
        ]
    )

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    artifacts = collect_artifacts()

    OUTPUT_FILE.write_text(
        generate_release_notes(artifacts),
        encoding="utf-8",
    )

    print(
        f"Release notes generated successfully: "
        f"{OUTPUT_FILE} ({len(artifacts)} artifact(s))"
    )


if __name__ == "__main__":
    main()